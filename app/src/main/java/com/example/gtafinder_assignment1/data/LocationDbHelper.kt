package com.example.gtafinder_assignment1.data

import android.content.ContentValues
import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteOpenHelper

/**
 * Creates and versions the local SQLite database that stores GTA locations.
 */
class LocationDbHelper(private val context: Context) :
    SQLiteOpenHelper(context, DATABASE_NAME, null, DATABASE_VERSION) {

    /** Called once, the first time the database file is created. */
    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL(SQL_CREATE_TABLE)
        seedLocations(db)
    }

    /** Called when DATABASE_VERSION goes up. For this assignment: rebuild the table. */
    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) {
        db.execSQL("DROP TABLE IF EXISTS $TABLE_LOCATION")
        onCreate(db)
    }

    private fun seedLocations(db: SQLiteDatabase) {
        context.assets.open(SEED_FILE).bufferedReader().useLines { lines ->
            lines.map { it.trim() }
                .filter { it.isNotEmpty() && !it.startsWith("#") }
                .forEach { line ->
                    val parts = line.split("|").map { it.trim() }
                    val latitude = parts.getOrNull(1)?.toDoubleOrNull()
                    val longitude = parts.getOrNull(2)?.toDoubleOrNull()
                    if (parts.size == 3 && latitude != null && longitude != null) {
                        val values = ContentValues().apply {
                            put(COLUMN_ADDRESS, parts[0])
                            put(COLUMN_LATITUDE, latitude)
                            put(COLUMN_LONGITUDE, longitude)
                        }
                        db.insert(TABLE_LOCATION, null, values)
                    }
                }
        }
    }

    companion object {
        const val DATABASE_NAME = "gta_finder.db"
        const val DATABASE_VERSION = 1

        const val TABLE_LOCATION = "location"
        const val COLUMN_ID = "id"
        const val COLUMN_ADDRESS = "address"
        const val COLUMN_LATITUDE = "latitude"
        const val COLUMN_LONGITUDE = "longitude"
        const val COLUMN_CREATED_DATETIME = "created_datetime"
        private const val SEED_FILE = "gta_locations.csv"

        // id is auto-generated by AUTOINCREMENT; created_datetime is auto-populated by DEFAULT.
        private val SQL_CREATE_TABLE = """
            CREATE TABLE $TABLE_LOCATION (
                $COLUMN_ID INTEGER PRIMARY KEY AUTOINCREMENT,
                $COLUMN_ADDRESS TEXT NOT NULL,
                $COLUMN_LATITUDE REAL NOT NULL,
                $COLUMN_LONGITUDE REAL NOT NULL,
                $COLUMN_CREATED_DATETIME TEXT NOT NULL DEFAULT (datetime('now', 'localtime'))
            )
        """.trimIndent()
    }
}